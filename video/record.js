// Records the ThreatWeigh demo video in three parts (webm), using Playwright.
//   node video/record.js <out_dir>
// Needs: the deck served at http://localhost:8600/deck.html and the Streamlit app at http://localhost:8599
const { chromium } = require('playwright');
const OUT = process.argv[2] || 'video/raw';
const SIZE = { width: 1280, height: 720 };
const sleep = ms => new Promise(r => setTimeout(r, ms));
const fs = require('fs');
let T0 = 0; const MARKS = [];
const mark = label => MARKS.push({ label, t: (Date.now() - T0) / 1000 });

async function recordDeck(browser, part) {
  const ctx = await browser.newContext({ viewport: SIZE, recordVideo: { dir: `${OUT}/deck${part}`, size: SIZE } });
  const page = await ctx.newPage();
  await page.goto(`http://localhost:8600/deck.html?part=${part}`);
  await page.waitForFunction(() => window.DONE === true, null, { timeout: 180000, polling: 500 });
  await ctx.close();
}

// A caption bar drawn on top of the real app (outside Streamlit's React tree, so reruns keep it).
async function caption(page, text) {
  await page.evaluate(t => {
    let el = document.getElementById('tw-cap');
    if (!el) {
      el = document.createElement('div');
      el.id = 'tw-cap';
      el.style.cssText = 'position:fixed;left:50%;bottom:22px;transform:translateX(-50%);z-index:99999;' +
        'background:rgba(15,20,32,.92);color:#f0efec;font:600 19px Inter,Helvetica,Arial,sans-serif;' +
        'padding:12px 22px;border-radius:12px;max-width:1100px;text-align:center;box-shadow:0 6px 24px rgba(0,0,0,.25);' +
        'transition:opacity .4s ease;';
      document.body.appendChild(el);
    }
    el.style.opacity = 0;
    setTimeout(() => { el.textContent = t; el.style.opacity = 1; }, 250);
  }, text);
}

async function scroll(page, dy, steps = 12, pause = 60) {
  await page.mouse.move(640, 380);
  for (let k = 0; k < steps; k++) { await page.mouse.wheel(0, dy / steps); await sleep(pause); }
}

async function predict(page, example) {
  await page.getByRole('button', { name: example, exact: true }).click();
  await sleep(1400);
  await page.getByRole('button', { name: 'Predict', exact: true }).click();
  await sleep(1500);
  mark('wait_start');               // Integrated Gradients for 8 models: ~30 s on CPU
  await page.getByText('Which words mattered?').waitFor({ timeout: 240000 });
  mark('wait_end');
  await sleep(800);
}

async function recordApp(browser) {
  const ctx = await browser.newContext({ viewport: SIZE, recordVideo: { dir: `${OUT}/app`, size: SIZE } });
  const page = await ctx.newPage();
  T0 = Date.now();
  await page.goto('http://localhost:8599', { waitUntil: 'networkidle' });
  await page.getByRole('button', { name: 'Predict', exact: true }).waitFor();
  // warm-up: load the 8 models once so the recorded prediction is fast
  await page.getByRole('button', { name: 'Predict', exact: true }).click();
  await page.getByText('Which words mattered?').waitFor({ timeout: 300000 });
  await page.reload({ waitUntil: 'networkidle' });
  await page.getByRole('button', { name: 'Predict', exact: true }).waitFor();
  await sleep(1500);
  mark('start');

  await caption(page, 'Step 4 · The Streamlit app (live): pick an example or paste any CVE description');
  await sleep(3500);
  await predict(page, 'Remote code execution');
  await caption(page, 'Unauthenticated remote code execution → AV:N/AC:L/PR:N/UI:N … → 9.8 Critical');
  await sleep(2500);
  await scroll(page, 330, 14, 70);
  await caption(page, 'All 8 metric models predict independently, each with its own confidence');
  await sleep(4000);
  await scroll(page, 520, 16, 70);
  await caption(page, 'Integrated Gradients: red = words the model relied on · underlined ◆ = expert-lexicon word');
  await sleep(5000);
  await scroll(page, 600, 18, 80);
  await sleep(3000);

  await scroll(page, -3000, 10, 40);
  await sleep(800);
  await caption(page, 'Second example: a stored XSS posted by a contributor-level user');
  await predict(page, 'Stored XSS');
  await sleep(2500);
  await scroll(page, 300, 12, 70);
  await caption(page, 'PR predicted High (63%): an honest failure. The attacker is a contributor (PR:Low)…');
  await sleep(4500);
  await scroll(page, 560, 16, 70);
  await sleep(1000);
  await page.evaluate(() => {
    const el = [...document.querySelectorAll('p, strong')].find(e => e.textContent.trim().startsWith('PR →'));
    if (el) el.scrollIntoView({ block: 'center', behavior: 'smooth' });
  });
  await sleep(1200);
  await caption(page, '…but “administrator” (a PR:High lexicon cue) dominates. The administrator is the victim here.');
  await sleep(6000);

  await scroll(page, -4000, 10, 40);
  await page.getByRole('tab', { name: 'Model results' }).click();
  await sleep(1500);
  await caption(page, 'Model results: every table and chart is generated by src/evaluate.py from the saved test predictions');
  await sleep(3500);
  await scroll(page, 420, 14, 80);
  await sleep(3500);
  await scroll(page, 520, 14, 80);
  await caption(page, 'Ablation and weight sensitivity: all variants within 0.11 percentage points');
  await sleep(4000);
  await scroll(page, 900, 18, 80);
  await caption(page, 'Paired bootstrap CIs and McNemar tests, temporal split, explanation-quality metrics');
  await sleep(4500);

  await scroll(page, -5000, 10, 40);
  await page.getByRole('tab', { name: 'How it works' }).click();
  await sleep(1200);
  await caption(page, 'How it works: a plain-language explanation and the pipeline diagram');
  await sleep(3500);
  await scroll(page, 450, 14, 80);
  await sleep(5000);
  mark('end');
  await ctx.close();
  fs.writeFileSync(`${OUT}/app_marks.json`, JSON.stringify(MARKS, null, 1));
}

(async () => {
  const browser = await chromium.launch();
  const which = process.argv[3] || 'all';
  if (which === 'all' || which === 'deck1') await recordDeck(browser, '1');
  if (which === 'all' || which === 'app') await recordApp(browser);
  if (which === 'all' || which === 'deck2') await recordDeck(browser, '2');
  await browser.close();
})().catch(e => { console.error(e); process.exit(1); });
